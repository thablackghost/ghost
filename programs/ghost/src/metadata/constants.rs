//! Constants for GHOST token metadata.

/// Token name (never changes).
pub const GHOST_NAME: &str = "GHOST";

/// Token symbol (never changes).
pub const GHOST_SYMBOL: &str = "GHOST";

/// Default token description.
pub const GHOST_DESCRIPTION: &str = "A meme token called GHOST.";

/// Maximum length for the token name field.
pub const MAX_NAME_LEN: usize = 32;

/// Maximum length for the token symbol field.
pub const MAX_SYMBOL_LEN: usize = 10;

/// Maximum length for the token URI field.
pub const MAX_URI_LEN: usize = 200;

/// Maximum length for the token description field.
pub const MAX_DESCRIPTION_LEN: usize = 500;
